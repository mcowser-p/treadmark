EXPECTED_CONTRACT = {
    "declarative_access_profile_name": "myapp",
    "declarative_access_sudo": True,
    "declarative_access_services": ["myapp", "myapp-agent", "myapp-maintenance"],
    "declarative_access_timers": ["myapp-maintenance"],
    "declarative_access_quadlets": ["myapp-web"],
    "declarative_access_linger": True,
    "declarative_access_linger_users": ["dev1"],
    "declarative_access_files_modify": [
        "/etc/containers/systemd/myapp-web.container",
        "/etc/systemd/system/myapp-agent.service",
        "/etc/systemd/system/myapp-maintenance.service",
        "/etc/systemd/system/myapp-maintenance.timer",
        "/etc/systemd/system/myapp.service",
    ],
    "declarative_access_folders_modify": ["/etc/myapp", "/var/lib/myapp"],
    "declarative_access_folders_read": ["/var/log/myapp"],
}


@pytest.fixture
def access_vars_run(run_cli, linux_rootfs, rootfs_config, tmp_path):
    """Init baseline, install the app, capture footprint + access vars."""
    root = linux_rootfs()
    cfg_path, _cfg = rootfs_config()
    rc, _out, _err = run_cli("files", "init", "-c", cfg_path,
                             "--root", str(root), "--force")
    assert rc == 0
    install_app(root)

    report = tmp_path / "footprint.json"
    vars_file = tmp_path / "myapp-access.yml"
    rc, _out, err = run_cli("footprint", "-c", cfg_path, "--root", str(root),
                            "--app", "myapp", "--report", str(report),
                            "--access-vars", str(vars_file))
    assert rc == 1  # changes present; the vars write does not alter drift rc
    assert "ansible access vars written" in err
    return report, vars_file.read_text(encoding="utf-8")


@pytestmark_linux
def test_contract_shape_matches_fixture(access_vars_run):
    _report, text = access_vars_run
    assert _load_vars(text) == EXPECTED_CONTRACT



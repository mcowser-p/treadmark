def _mk_model(**over) -> dict:
    model = {
        "schema_version": "1.0",
        "footprint_type": "install_time",
        "generated_at": "2026-01-01T00:00:00+00:00",
        "application": "myapp",
        "services": {"systemd_units": [], "quadlets": []},
        "filesystem": {"added_by_category": {}, "modified": [], "deleted": []},
        "principals": {"users_added": [], "groups_added": [],
                       "membership_changes": []},
    }
    model.update(over)
    return model


def _svc(name, path=None, unit_type=None, **fields) -> dict:
    unit = {"name": name,
            "path": path or f"/etc/systemd/system/{name}",
            "unit_type": unit_type or name.rsplit(".", 1)[-1]}
    unit.update(fields)
    return unit


def _entry(path, *, is_dir=False, owner="root", group="root",
           mode_octal="0o755") -> dict:
    return {"path": path, "is_dir": is_dir, "owner": owner, "group": group,
            "mode_octal": mode_octal, "category": "", "mode_symbolic": "",
            "size": 0, "sha256": None}


def test_ownership_emitted_for_install_added_principal():
    model = _mk_model()
    model["principals"]["users_added"] = [{"name": "myapp"}]
    model["filesystem"]["added_by_category"] = {
        "state_dir": [_entry("/var/lib/myapp", is_dir=True, owner="myapp",
                             group="myapp", mode_octal="0o2750")],
    }
    data = accessvars.derive_access_vars(model)
    assert data["declarative_access_ownership"] == [
        {"path": "/var/lib/myapp", "owner": "myapp", "group": "myapp",
         "mode": "2750"}]


def test_ownership_skipped_for_foreign_owner():
    model = _mk_model()
    model["filesystem"]["added_by_category"] = {
        "state_dir": [_entry("/var/lib/myapp", is_dir=True, owner="builder",
                             group="staff")],
    }
    data = accessvars.derive_access_vars(model)
    assert "declarative_access_ownership" not in data
    assert data["declarative_access_folders_modify"] == ["/var/lib/myapp"]


def test_ownership_mode_zero_padded():
    model = _mk_model()
    model["principals"]["groups_added"] = [{"name": "myapp"}]
    model["filesystem"]["added_by_category"] = {
        "config": [_entry("/etc/myapp", is_dir=True, group="myapp",
                          mode_octal="0o755")],
    }
    data = accessvars.derive_access_vars(model)
    assert data["declarative_access_ownership"][0]["mode"] == "0755"



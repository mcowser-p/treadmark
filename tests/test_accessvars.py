# ---------------------------------------------------------------------------
# Mini YAML-subset parser (scalars, block lists, one-line flow maps)
# ---------------------------------------------------------------------------

def _unq(v: str):
    if v == "true":
        return True
    if v == "false":
        return False
    if v.startswith("'") and v.endswith("'"):
        return v[1:-1].replace("''", "'")
    return v


def _load_vars(text: str) -> dict:
    data: dict = {}
    current = None
    for raw in text.splitlines():
        s = raw.strip()
        if not s or s.startswith("#") or s == "---":
            continue
        if raw.startswith("  - "):
            item = s[2:].strip()
            if item.startswith("{"):
                entry = {}
                for part in item.strip("{} ").split(","):
                    k, _, v = part.partition(":")
                    entry[k.strip()] = _unq(v.strip())
                data[current].append(entry)
            else:
                data[current].append(_unq(item))
        elif s.endswith(":"):
            current = s[:-1]
            data[current] = []
        else:
            k, _, v = s.partition(":")
            data[k.strip()] = _unq(v.strip())
    return data



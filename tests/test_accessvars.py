def test_folder_read_subsumed_by_modify_dropped():
    model = _mk_model()
    model["services"]["systemd_units"] = [
        _svc("app.service", state_directory=["myapp"]),
    ]
    model["filesystem"]["added_by_category"] = {
        "log_dir": [_entry("/var/lib/myapp/logs", is_dir=True)],
    }
    data = accessvars.derive_access_vars(model)
    assert data["declarative_access_folders_modify"] == ["/var/lib/myapp"]
    assert "declarative_access_folders_read" not in data


def test_files_under_granted_folder_dropped():
    model = _mk_model()
    model["filesystem"]["added_by_category"] = {
        "config": [_entry("/etc/myapp", is_dir=True)],
        "quadlet": [_entry("/etc/myapp/web.container"),
                    _entry("/etc/containers/systemd/web.container")],
    }
    data = accessvars.derive_access_vars(model)
    assert data["declarative_access_files_modify"] == [
        "/etc/containers/systemd/web.container"]


def test_directive_derived_folders_present_without_diff_entries():
    model = _mk_model()
    model["services"]["systemd_units"] = [
        _svc("app.service", state_directory=["myapp"],
             configuration_directory=["myapp"], cache_directory=["myapp"],
             logs_directory=["myapp"]),
    ]
    data = accessvars.derive_access_vars(model)
    assert data["declarative_access_folders_modify"] == [
        "/etc/myapp", "/var/cache/myapp", "/var/lib/myapp"]
    assert data["declarative_access_folders_read"] == ["/var/log/myapp"]


def test_empty_footprint_minimal_output():
    model = _mk_model()
    data = accessvars.derive_access_vars(model)
    assert data == {"declarative_access_profile_name": "myapp"}
    text = accessvars.render_access_vars(model)
    assert "no systemd service/timer/quadlet or folder surface" in text
    assert "declarative_access_sudo" not in text


def test_pyyaml_cross_parse():
    yaml = pytest.importorskip("yaml")
    model = _mk_model()
    model["services"]["systemd_units"] = [_svc("app.service"),
                                          _svc("nightly.timer")]
    model["services"]["quadlets"] = [
        {"name": "web.container", "service_name": "web.service",
         "rootless": False, "owner": None},
    ]
    model["principals"]["users_added"] = [{"name": "myapp"}]
    model["filesystem"]["added_by_category"] = {
        "state_dir": [_entry("/var/lib/myapp", is_dir=True, owner="myapp",
                             group="myapp", mode_octal="0o2750")],
        "systemd_unit": [_entry("/etc/systemd/system/app.service")],
    }
    text = accessvars.render_access_vars(model)
    assert yaml.safe_load(text) == _load_vars(text)

"""Tests for cairn.accessvars — the declarative_access vars exporter.

Two layers:
  - CLI end-to-end on the programmatic rootfs fixture (Linux/macOS only),
    pinning the cross-repo contract shape the linux-access molecule scenario
    mirrors in molecule/default/files/molecule-access-vars.yml.
  - Pure derive_access_vars() tests on synthetic model dicts — the rootfs
    fixture cannot fake file ownership without root, so ownership rules are
    exercised synthetically.

The emitted YAML is parsed back with a test-local mini-parser so the test
suite stays PyYAML-free; one importorskip'd test cross-checks against real
PyYAML when the dev environment has it.
"""

from __future__ import annotations

